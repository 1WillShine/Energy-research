def fig3_feature_importance(results: dict):
    """Horizontal bar chart of feature importances from GBM."""
    importances = results["experiments"]["classifier"]["feature_importances"]
    top_n = 12

    sorted_items = sorted(importances.items(), key=lambda x: x[1], reverse=True)[:top_n]
    features, values = zip(*sorted_items)

    # Clean feature names for publication
    name_map = {
        "lmp_zscore":      "LMP z-score (24h)",
        "lmp_lag1h":       "LMP lag 1h",
        "lmp_lag24h":      "LMP lag 24h",
        "lmp_roll24_mean": "LMP rolling mean (24h)",
        "lmp_roll24_std":  "LMP rolling std (24h)",
        "temp_f":          "Temperature (°F)",
        "temp_f_sq":       "Temperature² (nonlinear)",
        "heat_stress":     "Heat stress indicator (>95°F)",
        "temp_x_peak_hour":"Temp × peak hour",
        "hour":            "Hour of day",
        "solar_rad":       "Solar radiation",
        "wind_mph":        "Wind speed (mph)",
        "month":           "Month",
        "dow":             "Day of week",
        "is_summer":       "Summer indicator",
    }
    clean_names = [name_map.get(f, f) for f in features]

    fig, ax = plt.subplots(figsize=(7, 5))
    colors = [COLORS["heat"] if "temp" in f.lower() or "heat" in f.lower()
              else COLORS["global"] for f in features]

    bars = ax.barh(range(top_n), values[::-1] if False else values,
                   color=colors, alpha=0.85, edgecolor="white")
    ax.set_yticks(range(top_n))
    ax.set_yticklabels(clean_names, fontsize=9.5)
    ax.invert_yaxis()
    ax.set_xlabel("Feature Importance (GBM)", fontweight="bold")
    ax.set_title(
        "Figure 3: Feature Importances for Spike Classifier\n"
        "Orange = weather/temperature features",
        fontsize=10
    )

    # Add value labels
    for i, v in enumerate(values):
        ax.text(v + 0.001, i, f"{v:.3f}", va="center", fontsize=8)

    plt.tight_layout()
    path = FIGURES / "fig3_feature_importance.pdf"
    plt.savefig(path)
    plt.savefig(str(path).replace(".pdf", ".png"))
    print(f"  ✓ Figure 3 saved: {path.name}")
