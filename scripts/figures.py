def fig6_vulnerability_coverage_matrix(results: dict):
    """
    The paper's equity contribution figure.

    2×4 heatmap: vulnerability level × temperature regime → empirical coverage.
    Shows whether coverage gap is larger for high-vulnerability communities.
    This is Figure 6 — the social science layer of the paper.
    """
    if "vulnerability" not in results["experiments"]:
        print("  ⚠ Figure 6: vulnerability experiment not run yet")
        return

    vuln_exp = results["experiments"]["vulnerability"]
    if "error" in vuln_exp:
        print(f"  ⚠ Figure 6: {vuln_exp['error']}")
        return

    matrix = vuln_exp["coverage_matrix"]
    nominal = 1 - results["experiments"]["conformal_standard"]["alpha"]

    regimes    = ["<75°F", "75-90°F", "90-100°F", ">100°F"]
    vuln_labels = ["Low vulnerability", "High vulnerability"]

    # Build coverage grid
    global_grid = np.full((2, 4), np.nan)
    strat_grid  = np.full((2, 4), np.nan)
    n_grid      = np.full((2, 4), 0)

    for vi, vl in enumerate(vuln_labels):
        if vl not in matrix:
            continue
        for ri, regime in enumerate(regimes):
            cell = matrix[vl].get(regime, {})
            if cell and cell.get("global_coverage") is not None:
                global_grid[vi, ri] = cell["global_coverage"]
                strat_grid[vi, ri]  = cell["stratified_coverage"]
                n_grid[vi, ri]      = cell.get("n_spikes", 0)

    fig, axes = plt.subplots(1, 2, figsize=(12, 4.5))
    titles = ["Standard Conformal", "Stratified Conformal (Proposed)"]

    for ax, grid, title in zip(axes, [global_grid, strat_grid], titles):
        # Color: deviation from nominal (red = under-coverage, green = at/above)
        deviation = grid - nominal
        im = ax.imshow(deviation, cmap="RdYlGn", vmin=-0.3, vmax=0.3,
                       aspect="auto")

        ax.set_xticks(range(4))
        ax.set_xticklabels(regimes, fontsize=9.5)
        ax.set_yticks(range(2))
        ax.set_yticklabels(vuln_labels, fontsize=10)
        ax.set_title(title, fontweight="bold", fontsize=10)

        # Annotate cells
        for vi in range(2):
            for ri in range(4):
                val = grid[vi, ri]
                n   = n_grid[vi, ri]
                if not np.isnan(val):
                    color = "white" if abs(val - nominal) > 0.15 else "black"
                    ax.text(ri, vi, f"{val:.2f}\n(n={n})",
                            ha="center", va="center",
                            fontsize=8.5, color=color, fontweight="bold")
                else:
                    ax.text(ri, vi, "N/A", ha="center", va="center",
                            fontsize=8.5, color="gray")

        plt.colorbar(im, ax=ax, label="Coverage − Nominal", shrink=0.8)

    fig.suptitle(
        "Figure 6: Conformal Coverage by Vulnerability × Temperature Regime\n"
        f"Nominal coverage = {nominal:.0%}. Red = under-coverage, Green = at/above nominal.",
        fontsize=10, fontweight="bold", y=1.02
    )

    # Key finding annotation
    key = matrix.get("key_finding", {})
    disparity = key.get("coverage_disparity_extreme_heat")
    if disparity is not None:
        direction = "worse" if disparity > 0.02 else "comparable"
        fig.text(0.5, -0.04,
                 f"Coverage disparity (low vs high vuln, >100°F): {disparity:+.3f} "
                 f"→ High-vulnerability coverage is {direction} in extreme heat",
                 ha="center", fontsize=9, style="italic", color="darkred")

    plt.tight_layout()
    path = FIGURES / "fig6_vulnerability_coverage_matrix.pdf"
    plt.savefig(path)
    plt.savefig(str(path).replace(".pdf", ".png"))
    print(f"  ✓ Figure 6 saved: {path.name}")
    plt.close()


