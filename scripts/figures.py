def fig2_calibration_curves(results: dict):
    """
    Reliability diagram. Empirical probability vs. predicted probability.
    Perfect calibration = diagonal. Shows overall miscalibration.
    """
    clf = results["experiments"]["classifier"]
    train_cal = clf["train"]["calibration_fraction_pos"]
    train_pred = clf["train"]["calibration_mean_pred"]
    test_cal  = clf["test"]["calibration_fraction_pos"]
    test_pred = clf["test"]["calibration_mean_pred"]

    fig, ax = plt.subplots(figsize=(6, 5))

    ax.plot([0, 1], [0, 1], "k--", linewidth=1.2, label="Perfect calibration", zorder=1)
    ax.plot(train_pred, train_cal, "o-", color=COLORS["global"], linewidth=2,
            markersize=6, label="Train (2021-22)", alpha=0.9)
    ax.plot(test_pred, test_cal,  "s-", color=COLORS["stratified"], linewidth=2,
            markersize=6, label="Test (2024)", alpha=0.9)

    ax.fill_between([0, 1], [0, 1], [0, 1], alpha=0.03, color="gray")
    ax.set_xlabel("Mean Predicted Probability (spike)", fontweight="bold")
    ax.set_ylabel("Empirical Fraction of Positives", fontweight="bold")
    ax.set_title(
        "Figure 2: Classifier Calibration Curve\n"
        "Deviation from diagonal = miscalibration",
        fontsize=10
    )
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)

    # Print AUROC in legend
    train_auroc = clf["train"]["auroc"]
    test_auroc  = clf["test"]["auroc"]
    ax.text(0.98, 0.05,
            f"Train AUROC = {train_auroc:.3f}\nTest AUROC  = {test_auroc:.3f}",
            transform=ax.transAxes, ha="right", va="bottom",
            fontsize=9, bbox=dict(boxstyle="round,pad=0.3", facecolor="white", alpha=0.8))

    ax.legend(fontsize=9)
    plt.tight_layout()
    path = FIGURES / "fig2_calibration_curves.pdf"
    plt.savefig(path)
    plt.savefig(str(path).replace(".pdf", ".png"))
    print(f"  ✓ Figure 2 saved: {path.name}")
    plt.close()


