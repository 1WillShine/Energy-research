# Figure 4: LMP Time Series with Conformal Intervals (Sept 2022 heat wave)
# ═══════════════════════════════════════════════════════════════════════════════

def fig4_heat_wave_timeline(df: pd.DataFrame, results: dict):
    """
    Timeline figure: LMP prices + temperature + conformal prediction
    during September 2022 heat wave. This is the 'money figure' of the paper.
    """
    # September 2022 heat wave: Sep 1-15
    heat_period = df[
        (df["datetime"].dt.year == 2022) &
        (df["datetime"].dt.month == 9) &
        (df["datetime"].dt.day <= 15)
    ].copy().sort_values("datetime")

    if len(heat_period) == 0:
        print("  ⚠ Figure 4: Sept 2022 data not in dataset (data might start later)")
        return

    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(10, 7), sharex=True,
                                    gridspec_kw={"height_ratios": [2, 1]})

    # Top panel: LMP with spike highlighting
    ax1.plot(heat_period["datetime"], heat_period["lmp"],
             color=COLORS["global"], linewidth=1.2, label="LMP ($/MWh)", zorder=3)

    # Highlight spikes
    spikes = heat_period[heat_period["spike"] == 1]
    ax1.scatter(spikes["datetime"], spikes["lmp"],
                color=COLORS["heat"], s=20, zorder=4, label="Price spike (top 5%)", alpha=0.8)

    # Threshold line
    threshold_price = heat_period["lmp"].quantile(0.95)
    ax1.axhline(threshold_price, color=COLORS["heat"], linestyle=":",
                alpha=0.6, label=f"95th percentile (${threshold_price:.0f})")

    ax1.set_ylabel("LMP ($/MWh)", fontweight="bold")
    ax1.legend(fontsize=8.5, loc="upper left")
    ax1.set_title(
        "Figure 4: California LMP and Temperature — September 2022 Heat Wave\n"
        "Extreme temperatures drive LMP spikes outside model training distribution",
        fontsize=10
    )

    # Bottom panel: Temperature
    ax2.fill_between(heat_period["datetime"], heat_period["temp_f"],
                     alpha=0.4, color=COLORS["heat"])
    ax2.plot(heat_period["datetime"], heat_period["temp_f"],
             color=COLORS["heat"], linewidth=1.5, label="Temperature (°F)")
    ax2.axhline(95, color="darkred", linestyle="--", linewidth=1,
                label="95°F threshold (heat stress)")
    ax2.axhline(105, color="darkred", linestyle=":", linewidth=1,
                label="105°F threshold (extreme heat)")

    ax2.set_xlabel("Date", fontweight="bold")
    ax2.set_ylabel("Temperature (°F)", fontweight="bold")
    ax2.legend(fontsize=8.5, loc="upper left")

    # Shade the peak heat event dates (Sep 5-9)
    for ax in [ax1, ax2]:
        ax.axvspan(
            pd.Timestamp("2022-09-05", tz="UTC"),
            pd.Timestamp("2022-09-09", tz="UTC"),
            alpha=0.12, color="red", label="_nolegend_"
        )

    plt.tight_layout()
    path = FIGURES / "fig4_heatwave_timeline.pdf"
    plt.savefig(path)
    plt.savefig(str(path).replace(".pdf", ".png"))
    print(f"  ✓ Figure 4 saved: {path.name}")
    plt.close()


