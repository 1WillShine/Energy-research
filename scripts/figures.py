# Figure 5: Covariate Shift Detection
# ═══════════════════════════════════════════════════════════════════════════════

def fig5_covariate_shift(df: pd.DataFrame, results: dict):
    """
    Show temperature distribution shift between training (2021-22) and test (2024).
    Visually motivates why conformal coverage degrades.
    """
    train_temp = df[df["year"].isin([2021, 2022])]["temp_f"].dropna()
    test_temp  = df[df["year"] == 2024]["temp_f"].dropna()

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(10, 4.5))

    # Left: KDE / histogram comparison
    bins = np.linspace(train_temp.min(), max(train_temp.max(), test_temp.max()), 40)
    ax1.hist(train_temp, bins=bins, density=True, alpha=0.55,
             color=COLORS["global"], label="Train (2021-22)")
    ax1.hist(test_temp, bins=bins, density=True, alpha=0.55,
             color=COLORS["stratified"], label="Test (2024)")
    ax1.axvline(95, color="darkred", linestyle="--", linewidth=1.5, label="95°F threshold")
    ax1.set_xlabel("Temperature (°F)", fontweight="bold")
    ax1.set_ylabel("Density", fontweight="bold")
    ax1.set_title("Temperature Distribution Shift\n(Train vs. Test)", fontsize=10)
    ax1.legend(fontsize=9)

    # Right: AUROC from shift detection experiment
    shift = results["experiments"]["covariate_shift"]
    auroc = shift["auroc_mean"]
    std   = shift["auroc_std"]

    ax2.barh(["Shift detector AUROC"], [auroc], xerr=[std],
             color=COLORS["global"] if auroc < 0.7 else COLORS["stratified"],
             alpha=0.85, capsize=6, height=0.4)
    ax2.axvline(0.5, color="gray", linestyle="--", linewidth=1.2, label="Random (0.5)")
    ax2.axvline(0.7, color="darkred", linestyle=":", linewidth=1.2,
                label="Strong shift threshold (0.7)")
    ax2.set_xlim(0.4, 1.0)
    ax2.set_xlabel("AUROC (weather features only)", fontweight="bold")
    ax2.set_title(
        f"Classifier-Based Shift Detection\n"
        f"AUROC = {auroc:.3f} ± {std:.3f} → {shift['interpretation']}",
        fontsize=10
    )
    ax2.legend(fontsize=9)

    fig.suptitle("Figure 5: Covariate Shift in Weather Features (2021-22 → 2024)",
                 fontsize=11, fontweight="bold", y=1.02)
    plt.tight_layout()
    path = FIGURES / "fig5_covariate_shift.pdf"
    plt.savefig(path)
    plt.savefig(str(path).replace(".pdf", ".png"))
    print(f"  ✓ Figure 5 saved: {path.name}")
    plt.close()


