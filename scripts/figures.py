# Figure 1: Coverage Degradation — Main Result
# ═══════════════════════════════════════════════════════════════════════════════

def fig1_coverage_degradation(results: dict):
    """
    Main paper figure. Shows empirical coverage by temperature regime
    for standard conformal vs. stratified conformal vs. nominal.
    """
    exp = results["experiments"]
    alpha = exp["conformal_standard"]["alpha"]
    nominal = 1 - alpha

    regimes = ["<75°F", "75-90°F", "90-100°F", ">100°F"]
    std_cov  = []
    strat_cov = []
    n_spikes  = []

    comparison = exp["conformal_stratified"]["coverage_comparison"]
    for r in regimes:
        if r in comparison:
            std_cov.append(comparison[r]["global_coverage"])
            strat_cov.append(comparison[r]["stratified_coverage"])
            n_spikes.append(comparison[r]["n_spikes"])
        else:
            std_cov.append(np.nan)
            strat_cov.append(np.nan)
            n_spikes.append(0)

    x = np.arange(len(regimes))
    width = 0.32

    fig, ax = plt.subplots(figsize=(8, 5))

    bars1 = ax.bar(x - width/2, std_cov,  width, label="Standard conformal",
                   color=COLORS["global"], alpha=0.85, edgecolor="white")
    bars2 = ax.bar(x + width/2, strat_cov, width, label="Stratified conformal (ours)",
                   color=COLORS["stratified"], alpha=0.85, edgecolor="white")

    # Nominal coverage line
    ax.axhline(nominal, color=COLORS["nominal"], linestyle="--", linewidth=1.8,
               label=f"Nominal coverage ({nominal:.0%})", zorder=5)

    # Annotate sample sizes
    for i, n in enumerate(n_spikes):
        if n > 0:
            ax.text(x[i], 0.02, f"n={n}", ha="center", va="bottom",
                    fontsize=8.5, color="white", fontweight="bold")

    ax.set_xticks(x)
    ax.set_xticklabels(regimes)
    ax.set_xlabel("Temperature Regime", fontweight="bold")
    ax.set_ylabel("Empirical Coverage", fontweight="bold")
    ax.set_title(
        "Figure 1: Conformal Coverage Degrades Under High Temperature\n"
        "Standard conformal fails in high-heat regimes; stratified calibration restores coverage",
        fontsize=10, pad=12
    )
    ax.set_ylim(0, 1.1)
    ax.axhspan(0, nominal - 0.05, alpha=0.04, color="red", label="Under-coverage zone")
    ax.legend(loc="lower left", fontsize=9)

    plt.tight_layout()
    path = FIGURES / "fig1_coverage_degradation.pdf"
    plt.savefig(path)
    plt.savefig(str(path).replace(".pdf", ".png"))
    print(f"  ✓ Figure 1 saved: {path.name}")
    plt.close()


